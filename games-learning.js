  function explain(lesson, q) {
    const meta = lessons[lesson];
    const prompt = String(q.question || q.left || q.clue || q.statement || "");
    const bank = window.gameQuestionBank?.[lesson];
    const canonical = bank?.quickAnswer || [];
    let i = canonical.findIndex(
      (x) =>
        prompt.includes(
          String(x.question).replace(/\.\s*[xyz]\s*=\s*\?/g, ""),
        ) || String(x.question).includes(prompt),
    );
    if (i < 0)
      i = canonical.findIndex(
        (x) =>
          String(x.answer) ===
          String(q.answer ?? q.right).replace(/^[xyz]\s*=\s*/, ""),
      );
    if (lesson === "7-algebra-1-1" && q.statement)
      return {
        hint: meta[1],
        solution: q.statement.includes("2 : 3")
          ? "2 × 9 = 18, ал 8 × 3 = 24: тең емес. 2 : 3 = 6 : 9, өйткені 2 × 9 = 3 × 6 = 18."
          : "4 × 15 = 60, ал 5 × 8 = 40: тең емес. 4 : 5 = 8 : 10, өйткені 4 × 10 = 5 × 8 = 40.",
      };
    if (lesson === "7-algebra-1-1" && prompt.includes("6 : 4"))
      return { hint: meta[1], solution: "6 : 4 = x : 10 ⇒ 4x = 60 ⇒ x = 15." };
    if (lesson === "7-algebra-1-1" && prompt.includes("7 : 3"))
      return { hint: meta[1], solution: "7 : 3 = 14 : x ⇒ 7x = 42 ⇒ x = 6." };
    return {
      hint: meta?.[1] || "Берілген шамалар мен амалдарды ретімен тексер.",
      solution:
        meta?.[2]?.[i] ||
        String(
          q.correction ||
            q.answer ||
            q.right ||
            "Бұл тапсырманың толық шешімі әзірленбеген.",
        ),
    };
  }
  window.GameLearning = { lessons, rules, explain };
