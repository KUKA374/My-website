  function start() {
    if (typeof lessonContent === 'undefined') return;
    var quarters = ['q1', 'q2', 'q3', 'q4'];
    quarters.forEach(function (q) {
      var lessons = window.ktpD && window.ktpD['6_math_' + q];
      if (Array.isArray(lessons)) {
        lessons.forEach(function (x) {
          lessonContent['6_math_' + x.quarter + '_' + x.lesson] = make(x);
        });
      }
    });
    window.lessonContent6Ready = true;
  }

